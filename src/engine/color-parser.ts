// Convert RGB / RGBA string into parsed ColorValue
export function parseColor(colorStr: string, element?: HTMLElement, propertyName?: string): ColorValue {
  if (!colorStr || colorStr === 'transparent' || colorStr === 'rgba(0, 0, 0, 0)') {
    return {
      hex: 'transparent',
      rgb: 'transparent',
      hsl: 'transparent',
      alpha: 0,
      raw: colorStr || 'transparent'
    };
  }

  // Check if color is hex
  if (colorStr.startsWith('#')) {
    const hex = colorStr;
    const { r, g, b, a } = hexToRgba(hex);
    const rgb = a === 1 ? `rgb(${r}, ${g}, ${b})` : `rgba(${r}, ${g}, ${b}, ${a.toFixed(2)})`;
    const hsl = rgbToHsl(r, g, b);
    return {
      hex,
      rgb,
      hsl,
      alpha: a,
      raw: colorStr,
      tailwindClass: matchTailwindColor(hex)
    };
  }

  // Check rgb/rgba pattern
  const rgbaMatch = colorStr.match(/rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)(?:\s*,\s*([\d.]+))?\s*\)/);
  if (rgbaMatch) {
    const r = Math.round(parseFloat(rgbaMatch[1]));
    const g = Math.round(parseFloat(rgbaMatch[2]));
    const b = Math.round(parseFloat(rgbaMatch[3]));
    const a = rgbaMatch[4] !== undefined ? parseFloat(rgbaMatch[4]) : 1;

    const hex = rgbaToHex(r, g, b, a);
    const rgb = a === 1 ? `rgb(${r}, ${g}, ${b})` : `rgba(${r}, ${g}, ${b}, ${a})`;
    const hsl = rgbToHsl(r, g, b);

    let tailwindClass = matchTailwindColor(hex);
    if (!tailwindClass && a === 1) {
      tailwindClass = matchTailwindColor(hex.slice(0, 7));
    }

    return {
      hex,
      rgb,
      hsl,
      alpha: a,
      raw: colorStr,
      tailwindClass
    };
  }

  return {
    hex: colorStr,
    rgb: colorStr,
    hsl: colorStr,
    alpha: 1,
    raw: colorStr
  };
}

function hexToRgba(hex: string): { r: number; g: number; b: number; a: number } {
  let cleanHex = hex.replace('#', '');
  if (cleanHex.length === 3) {
    cleanHex = cleanHex.split('').map(c => c + c).join('');
  }
  if (cleanHex.length === 6) {
    const num = parseInt(cleanHex, 16);
    return { r: (num >> 16) & 255, g: (num >> 8) & 255, b: num & 255, a: 1 };
  }
  if (cleanHex.length === 8) {
    const num = parseInt(cleanHex, 16);
    return {
      r: (num >> 24) & 255,
      g: (num >> 16) & 255,
      b: (num >> 8) & 255,
      a: Math.round(((num & 255) / 255) * 100) / 100
    };
  }
  return { r: 0, g: 0, b: 0, a: 1 };
}

function rgbaToHex(r: number, g: number, b: number, a = 1): string {
  const toHex = (n: number) => {
    const hex = Math.max(0, Math.min(255, n)).toString(16);
    return hex.length === 1 ? '0' + hex : hex;
  };
  const base = `#${toHex(r)}${toHex(g)}${toHex(b)}`;
  if (a < 1) {
    const alphaHex = toHex(Math.round(a * 255));
    return `${base}${alphaHex}`;
  }
  return base;
}

function rgbToHsl(r: number, g: number, b: number): string {
  r /= 255;
  g /= 255;
  b /= 255;
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  let h = 0;
  let s = 0;
  const l = (max + min) / 2;

  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    switch (max) {
      case r: h = (g - b) / d + (g < b ? 6 : 0); break;
      case g: h = (b - r) / d + 2; break;
      case b: h = (r - g) / d + 4; break;
    }
    h /= 6;
  }

  return `hsl(${Math.round(h * 360)}, ${Math.round(s * 100)}%, ${Math.round(l * 100)}%)`;
}

function matchTailwindColor(hex: string): string | undefined {
  const normHex = hex.toLowerCase().slice(0, 7);
  for (const [name, colorHex] of Object.entries(TAILWIND_COLORS)) {
    if (colorHex.toLowerCase() === normHex) {
      return name;
    }
  }
  return undefined;
}

// Convert pixel string (e.g. "16px") to rem string (e.g. "1rem")
export function pxToRem(pxStr: string): string {
  const px = parseFloat(pxStr);
  if (isNaN(px)) return pxStr;
  const rem = px / 16;
  return `${Number(rem.toFixed(3))}rem`;
}

// Match border-radius pixel value to standard Tailwind rounded classes
export function matchTailwindRounded(radiusStr: string): string | undefined {
  const px = parseFloat(radiusStr);
  if (isNaN(px) || px === 0) return 'rounded-none';
  if (px <= 2) return 'rounded-sm';
  if (px <= 4) return 'rounded';
  if (px <= 6) return 'rounded-md';
  if (px <= 8) return 'rounded-lg';
  if (px <= 12) return 'rounded-xl';
  if (px <= 16) return 'rounded-2xl';
  if (px <= 24) return 'rounded-3xl';
  if (px >= 9999 || px > 100) return 'rounded-full';
  return undefined;
}
